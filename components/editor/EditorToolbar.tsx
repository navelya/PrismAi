'use client';

import React, { useState } from 'react';
import { Play, Save, Trash2, FilePlus, MoreVertical, MousePointer, Square, Coins, Loader2, AlertCircle } from 'lucide-react';
import { useExecutionValidation } from '@/lib/hooks/use-execution-validation';
import { formatValidationError } from '@/lib/workflow/validate-execution-messages';
import { Tooltip } from '@/components/ui/Tooltip';
import { useTokenBalance } from '@/lib/billing/use-balance';
import { formatCredits } from '@/lib/billing/cost';
import PlansModal from '@/components/billing/PlansModal';
import { useAppStore } from '@/lib/store/app-store';

interface EditorToolbarProps {
    workflowName: string;
    onNameChange: (name: string) => void;
    onSave: () => void;
    onRun: () => void;
    onStop?: () => void;
    isRunning?: boolean;
    onDelete: () => void;
    onNew: () => void;
    isPaletteOpen?: boolean;
}

export default function EditorToolbar({
    workflowName,
    onNameChange,
    onSave,
    onRun,
    onStop,
    isRunning = false,
    onDelete,
    onNew,
    isPaletteOpen = true,
}: EditorToolbarProps) {
    const [showMenu, setShowMenu] = useState(false);
    const [showPlans, setShowPlans] = useState(false);
    const { balance, loading: balanceLoading } = useTokenBalance();
    // Bulk-download progress (multi-select toolbar → "Download selected").
    // One pill per active operation so concurrent downloads stack side by
    // side rather than fight over a single indicator. Keys are stable
    // per-call ids generated by EditorCanvas.
    const bulkDownloads = useAppStore((s) => s.bulkDownloads);
    const activeDownloadEntries = Object.entries(bulkDownloads);
    const { errors: validationErrors } = useExecutionValidation();
    const selectNodeAndCenter = useAppStore((s) => s.selectNodeAndCenter);
    const [showErrorPopover, setShowErrorPopover] = useState(false);
    // State for auto-expanding width
    const [titleWidth, setTitleWidth] = useState('auto');
    const spanRef = React.useRef<HTMLSpanElement>(null);

    React.useEffect(() => {
        if (spanRef.current) {
            const width = spanRef.current.offsetWidth;
            setTitleWidth(`${Math.max(120, Math.min(width + 32, 400))}px`);
        }
    }, [workflowName]);

    // Floating Island CSS Classes
    const islandBase = "pointer-events-auto bg-surface-elevated/80 backdrop-blur-md border border-stroke-subtle shadow-xl shadow-black/20 transition-all duration-500 ease-in-out px-2 py-1.5 flex items-center gap-2";

    return (
        <div className="absolute inset-0 z-40 p-4 pointer-events-none flex items-start">
            {/* Hidden span for width measurement */}
            <span
                ref={spanRef}
                className="absolute opacity-0 pointer-events-none whitespace-pre font-semibold text-sm px-4"
                aria-hidden="true"
            >
                {workflowName || "Untitled Workflow"}
            </span>

            {/* Credits Island (Left) */}
            <div className={`${islandBase} rounded-xl pl-3 pr-1.5`}>
                <div className="flex items-center gap-1.5 text-sm font-semibold text-content-primary tabular-nums">
                    <Coins className="w-4 h-4 text-accent-primary" />
                    <span>{balanceLoading ? '…' : formatCredits(balance)}</span>
                </div>
                <div className="w-[1px] h-4 bg-stroke-subtle mx-1" />
                <button
                    onClick={() => setShowPlans(true)}
                    className="px-3 py-1 text-xs font-semibold text-accent-primary hover:bg-accent-primary/10 rounded-full transition-colors"
                >
                    Upgrade
                </button>
            </div>

            <PlansModal isOpen={showPlans} onClose={() => setShowPlans(false)} />

            {/* Workflow Name Island (Centered) */}
            <div
                className={`${islandBase} rounded-xl absolute left-1/2 -translate-x-1/2`}
                style={{ width: titleWidth }}
            >
                <div className="flex items-center gap-2 w-full justify-center px-1">
                    <div className="w-1.5 h-1.5 rounded-full bg-accent-primary animate-pulse flex-shrink-0" />
                    <input
                        type="text"
                        value={workflowName || ''}
                        onChange={(e) => onNameChange(e.target.value)}
                        className="w-full bg-transparent text-sm font-semibold text-content-primary placeholder:text-content-tertiary focus:outline-none text-center"
                        placeholder="Untitled Workflow"
                    />
                </div>
            </div>

            <div className="flex-1" />

            {/* Actions Island (Right) — minimal */}
            <div className="pointer-events-auto bg-surface-elevated/80 backdrop-blur-md border border-stroke-subtle shadow-lg rounded-xl px-1.5 py-1 flex items-center gap-1 transition-colors">
                {activeDownloadEntries.map(([opId, progress]) => {
                    const percent = progress.total > 0
                        ? Math.min(100, Math.round((progress.current / progress.total) * 100))
                        : null;
                    return (
                        <Tooltip
                            key={opId}
                            content={percent !== null ? `Preparing zip · ${percent}%` : 'Preparing zip…'}
                            position="bottom"
                        >
                            <div className="h-8 px-2.5 flex items-center gap-1.5 rounded-lg bg-white/5 border border-stroke-subtle text-content-secondary text-[11px] font-bold uppercase tracking-wider">
                                <Loader2 className="w-3 h-3 animate-spin text-accent-primary" />
                                <span className="tabular-nums">
                                    {percent !== null ? `${percent}%` : '…'}
                                </span>
                            </div>
                        </Tooltip>
                    );
                })}
                {/* Primary CTA: Run / Stop — kept prominent */}
                {isRunning ? (
                    <Tooltip content="Stop workflow" position="bottom">
                        <button
                            onClick={onStop}
                            className="h-8 px-3 bg-accent-error/15 border border-accent-error/30 hover:bg-accent-error/25 text-accent-error rounded-lg flex items-center gap-1.5 font-bold uppercase tracking-wider text-[11px] active:scale-95 transition-colors"
                        >
                            <Square className="w-3 h-3 fill-current" />
                            Stop
                        </button>
                    </Tooltip>
                ) : (
                    <div
                        className="relative"
                        onMouseEnter={() => validationErrors.length > 0 && setShowErrorPopover(true)}
                        onMouseLeave={() => setShowErrorPopover(false)}
                    >
                        <button
                            onClick={onRun}
                            className="h-8 px-3 bg-accent-primary hover:bg-accent-primary/90 text-white rounded-lg flex items-center gap-1.5 font-bold uppercase tracking-wider text-[11px] shadow-md shadow-accent-primary/20 active:scale-95 transition-colors"
                        >
                            <Play className="w-3 h-3 fill-current" />
                            Run workflow
                        </button>

                        {validationErrors.length > 0 && (
                            <div
                                className="absolute -top-1.5 -right-1.5 z-20 flex items-center justify-center min-w-[18px] h-[18px] px-1 rounded-full bg-accent-error text-white text-[10px] font-bold border-2 border-surface-elevated shadow-md tabular-nums pointer-events-none"
                                aria-label={`${validationErrors.length} validation errors`}
                            >
                                {validationErrors.length}
                            </div>
                        )}

                        {showErrorPopover && validationErrors.length > 0 && (
                            <div className="absolute top-full right-0 w-80 max-h-96 overflow-y-auto bg-surface-elevated/95 backdrop-blur-md border border-stroke-subtle rounded-xl shadow-xl shadow-black/20 z-30 p-2">
                                <div className="px-2 py-1.5 text-[11px] font-bold uppercase tracking-wider text-content-tertiary">
                                    Can&apos;t run — {validationErrors.length} issue{validationErrors.length === 1 ? '' : 's'}
                                </div>
                                <div className="flex flex-col gap-0.5">
                                    {validationErrors.map((e, i) => (
                                        <button
                                            key={i}
                                            onClick={() => {
                                                selectNodeAndCenter(e.nodeId);
                                                setShowErrorPopover(false);
                                            }}
                                            className="text-left px-2 py-1.5 rounded-md hover:bg-white/5 transition-colors flex items-start gap-2"
                                        >
                                            <AlertCircle className="w-3.5 h-3.5 mt-0.5 text-accent-error flex-shrink-0" />
                                            <div className="min-w-0 flex-1">
                                                <div className="text-xs font-semibold text-content-primary truncate">{e.nodeLabel}</div>
                                                <div className="text-[11px] text-content-secondary">{formatValidationError(e)}</div>
                                            </div>
                                        </button>
                                    ))}
                                </div>
                            </div>
                        )}
                    </div>
                )}

                <div className="w-px h-4 bg-stroke-subtle mx-0.5" />

                <Tooltip content="Save" position="bottom">
                    <button
                        onClick={onSave}
                        className="p-1.5 text-content-tertiary hover:text-content-primary hover:bg-white/10 rounded-md transition-colors"
                    >
                        <Save className="w-3.5 h-3.5" />
                    </button>
                </Tooltip>

                <Tooltip content="New" position="bottom">
                    <button
                        onClick={onNew}
                        className="p-1.5 text-content-tertiary hover:text-content-primary hover:bg-white/10 rounded-md transition-colors"
                    >
                        <FilePlus className="w-3.5 h-3.5" />
                    </button>
                </Tooltip>

                {/* More Menu */}
                <div className="relative">
                    <button
                        onClick={() => setShowMenu(!showMenu)}
                        className="p-1.5 text-content-tertiary hover:text-content-primary hover:bg-white/10 rounded-md transition-colors"
                    >
                        <MoreVertical className="w-3.5 h-3.5" />
                    </button>

                    {showMenu && (
                        <>
                            <div className="fixed inset-0 z-10" onClick={() => setShowMenu(false)} />
                            <div className="absolute right-0 top-full mt-1.5 w-44 bg-surface-primary/95 backdrop-blur-xl border border-white/10 rounded-xl shadow-2xl ring-1 ring-white/5 z-20 p-1 overflow-hidden">
                                <button
                                    onClick={() => { onDelete(); setShowMenu(false); }}
                                    className="w-full flex items-center gap-2 px-2 py-1.5 rounded-lg text-[11px] font-semibold text-red-400 hover:bg-red-500/10 transition-colors"
                                >
                                    <Trash2 className="w-3.5 h-3.5" />
                                    Delete Workflow
                                </button>
                            </div>
                        </>
                    )}
                </div>
            </div>
        </div>
    );
}
